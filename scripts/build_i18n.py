#!/usr/bin/env python3
"""Generate /pt-br/index.html and /en/index.html from the root index.html.

index.html is the only file to edit. Every translatable element carries
data-pt / data-en, and head meta tags carry data-en-content. This script
writes a fully translated static page per language, so link previews,
search engines and AI crawlers see the right language without running JS.

    python3 scripts/build_i18n.py          # write both pages
    python3 scripts/build_i18n.py --check  # exit 1 if they are out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://guedesfelipe.github.io"
SOURCE = ROOT / "index.html"
NOTICE = "<!-- Generated by scripts/build_i18n.py from /index.html. Do not edit. -->\n"

# A leaf element whose text is swapped: <tag ... data-pt="…" ... data-en="…" ...>text</tag>
LEAF = re.compile(
    r'(<(?P<tag>[a-zA-Z0-9]+)\b(?P<attrs>[^>]*?\sdata-pt="[^"]*"[^>]*)>)(?P<text>[^<]*)(</(?P=tag)>)'
)
META = re.compile(r'(<meta\b[^>]*?\scontent=")([^"]*)("[^>]*?\sdata-en-content="([^"]*)"[^>]*>)')


def replace_once(html: str, old: str, new: str) -> str:
    if html.count(old) != 1:
        raise SystemExit(f"build_i18n: expected exactly one {old!r} in index.html")
    return html.replace(old, new)


def replace_all(html: str, old: str, new: str) -> str:
    if old not in html:
        raise SystemExit(f"build_i18n: expected {old!r} in index.html")
    return html.replace(old, new)


def to_english(html: str) -> str:
    expected = len(re.findall(r'\sdata-pt="', html))

    def swap(m):
        en = re.search(r'\sdata-en="([^"]*)"', m.group("attrs"))
        if not en:
            raise SystemExit(f"build_i18n: data-pt without data-en: {m.group(1)[:80]}")
        return m.group(1) + en.group(1) + m.group(5)

    html, n = LEAF.subn(swap, html)
    if n != expected:
        raise SystemExit(f"build_i18n: swapped {n} of {expected} data-pt elements (one has child markup?)")
    html = META.sub(lambda m: m.group(1) + m.group(4) + m.group(3), html)

    html = replace_once(html, '<html lang="pt-BR">', '<html lang="en">')
    html = replace_once(html, '<meta property="og:locale" content="pt_BR">', '<meta property="og:locale" content="en_US">')
    html = replace_once(html, '<meta property="og:locale:alternate" content="en_US">', '<meta property="og:locale:alternate" content="pt_BR">')
    html = replace_once(html, f'<link rel="canonical" href="{SITE}/pt-br/">', f'<link rel="canonical" href="{SITE}/en/">')
    html = replace_once(html, f'<meta property="og:url" content="{SITE}/pt-br/">', f'<meta property="og:url" content="{SITE}/en/">')
    html = replace_once(
        html,
        'id="langToggle" href="/en/" hreflang="en" lang="en" onclick="toggleLanguage(event)" aria-label="Read in English"',
        'id="langToggle" href="/pt-br/" hreflang="pt-BR" lang="pt-BR" onclick="toggleLanguage(event)" aria-label="Ler em português"',
    )
    html = replace_once(html, '<span id="langButton">EN</span>', '<span id="langButton">PT-BR</span>')
    html = replace_once(html, f'id="siteLink" href="{SITE}/pt-br/"', f'id="siteLink" href="{SITE}/en/"')
    html = replace_all(html, 'aria-label="Pausar a aurora">Pausar</button>', 'aria-label="Pause the aurora">Pause</button>')
    html = replace_once(html, '<nav aria-label="Trajetória">', '<nav aria-label="Career">')
    html = replace_once(html, 'role="img" aria-label="atual"', 'role="img" aria-label="current"')
    html = replace_once(html, 'data-start="2023-07-01">Jul 2023 até hoje<', 'data-start="2023-07-01">Jul 2023 to present<')
    return html


def stamp(html: str) -> str:
    # the pages live one folder down, so the shared stylesheets are one level up
    html = replace_once(html, '@import url("./tokens.css");', '@import url("../tokens.css");')
    html = replace_once(html, '@import url("./base.css");', '@import url("../base.css");')
    # after the doctype, so the page stays in standards mode
    return replace_once(html, "<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + NOTICE)


def build() -> dict:
    src = SOURCE.read_text(encoding="utf-8")
    return {
        ROOT / "pt-br" / "index.html": stamp(src),
        ROOT / "en" / "index.html": stamp(to_english(src)),
    }


def main() -> None:
    pages = build()
    if "--check" in sys.argv:
        stale = [p for p, html in pages.items() if not p.exists() or p.read_text(encoding="utf-8") != html]
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        sys.exit(1 if stale else 0)
    for path, html in pages.items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(html, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
